const T = typograph;

export function Guide({ onOpenSection }: { onOpenSection: (id: string) => void }) {
  const [open, setOpen] = useState<string | null>('basics');
  return (
    <div className="space-y-3">
      {LESSONS.map((lesson, n) => {
        const isOpen = open === lesson.id;
        return (
          <section key={lesson.id} className="rounded-[16px] bg-white border border-[#1d1b19]/[0.08]">
            <button type="button" onClick={() => setOpen(isOpen ? null : lesson.id)} className="w-full flex items-start gap-3 p-4 sm:p-5 text-left cursor-pointer">
              <span className="w-8 h-8 shrink-0 rounded-full bg-[#c98a35]/15 text-[#9a6418] text-[14px] font-semibold flex items-center justify-center">{n + 1}</span>
              <span className="flex-1 min-w-0">
                <span className="block text-[16px] font-semibold leading-[1.35]">{T(lesson.title)}</span>
                <span className="block mt-0.5 text-[13px] text-[#1d1b19]/55">{T(lesson.when)}</span>
              </span>
              {isOpen ? <ChevronDown className="w-5 h-5 mt-1 shrink-0" /> : <ChevronRight className="w-5 h-5 mt-1 shrink-0" />}
            </button>
            {isOpen && (
              <div className="px-4 sm:px-5 pb-5 sm:pl-[64px]">
                <ol className="space-y-2.5">
                  {lesson.steps.map((step, i) => (
                    <li key={i} className="flex gap-3 text-[14px] leading-[1.6]">
                      <span className="w-5 shrink-0 text-right font-semibold text-[#9a6418]">{i + 1}.</span>
                      <span>{T(step)}</span>
                    </li>
                  ))}
                </ol>
                {lesson.tips && (
                  <div className="mt-4 rounded-[12px] bg-[#fff4dc] p-3.5 space-y-1.5">
                    {lesson.tips.map((tip, i) => (
                      <p key={i} className="flex gap-2 text-[13px] leading-[1.55] text-[#6b4a0e]">
                        <Lightbulb className="w-4 h-4 mt-0.5 shrink-0" /> <span>{T(tip)}</span>
                      </p>
                    ))}
                  </div>
                )}
                {lesson.section && (
                  <button
                    type="button"
                    onClick={() => onOpenSection(lesson.section!.id)}
                    className="mt-4 inline-flex items-center gap-1.5 rounded-[10px] bg-[#1d1b19] text-white px-3.5 py-2 text-[13px] font-semibold cursor-pointer"
                  >
                    {lesson.section.label} <ArrowRight className="w-4 h-4" />
                  </button>
                )}
              </div>
            )}
          </section>
        );
      })}
    </div>
  );
}
